# Akari Valley (Chapter 1) level builder -> src/scenes/level1Map.ts
# chars: # solid  = stone one-way ledge  w waterfall column  f flower(memory)  J jet-boots pickup  P start
# enemies d drone b bot t turret K boss.  props R r trees L lantern S shrine(checkpoint) T torii C car B bush A arch F fence G gate
# Rows: H=32, ground G=28. Jumps: single ~4.7 tiles, double ~8.3, double+jet ~13 (tests/reach.mjs verifies JET checks).
W, H, G = 470, 32, 28
M = [['.'] * W for _ in range(H)]
top = [G] * W
ents = []; JET = []; DBL = []
def ground(a, b, h):
    for x in range(a, b): top[x] = h
def pit(a, b):
    for x in range(a, b): top[x] = None
def on(x, c, dy=0): ents.append((x, c, dy))
def plat(x, y, n): 
    for i in range(n): M[y][x + i] = '='
def block(x0, y0, x1, y1):  # solid floating stone mass (inclusive cols x0..x1-1, rows y0..y1-1)
    for y in range(y0, y1):
        for x in range(x0, x1): M[y][x] = '#'
def put(x, y, c): M[y][x] = c
# --- 0-44 quiet intro; jet boots pickup ---
on(3, 'R'); on(9, 'B'); on(14, 'F'); on(17, 'L'); put(22, G - 2, 'f')                 # memory 1
ground(26, 32, 27); ground(32, 40, 26); on(30, 'B'); on(37, 'r'); on(34, 'J', -1)     # jet boots on the step
plat(40, 22, 4); put(41, 21, 'f'); DBL.append((38, 26, 41, 22))                       # memory 2 (double jump)
# --- 44-62 lake bridge ---
pit(46, 53); on(42, 'L'); on(56, 'F')
# --- 62-110 terraces + high route (jet) ---
ground(62, 70, 27); ground(70, 78, 25); ground(78, 96, 23); ground(96, 104, 26)
on(66, 'B'); on(74, 'r'); on(92, 'R'); on(88, 'd', -4); on(100, 'b')
block(80, 12, 90, 14); put(84, 11, 'f'); JET.append((80, 23, 84, 12))                  # memory 3: high route, jet only (11 tiles)
plat(92, 15, 6); plat(100, 13, 5)                                                     # high route continues
# --- 110-140 waterfall chasm: low one-ways, high stone ledges ---
pit(110, 136); plat(113, 25, 4); plat(120, 23, 4); plat(127, 25, 4); plat(132, 22, 3)
block(107, 17, 112, 18); block(117, 15, 121, 16); block(125, 16, 129, 17); JET.append((105, 28, 108, 17))           # high route over the chasm
put(119, 14, 'f')                                                                     # memory 4 (high route)
put(122, 21, '.');
for x in (115, 124, 131): put(x, 10, 'w')
on(118, 'd', -14)
# --- 136-170 lantern-shrine checkpoint ---
ground(136, 170, 27); on(140, 'A'); on(150, 'S'); on(156, 'L'); on(162, 'R'); on(146, 'F'); put(166, G - 4, 'f')  # memory 5
# --- 170-250 rising pressure: tall multi-tier tower ---
ground(170, 180, 25); ground(180, 190, 23); pit(190, 196); ground(196, 210, 24); ground(210, 222, 27); ground(222, 236, 25); ground(236, 250, 27)
block(178, 18, 184, 19); block(186, 9, 192, 10); put(189, 8, 'f'); JET.append((183, 18, 188, 9))   # memory 6: climb tower (jet from tier)
DBL.append((180, 23, 180, 18))
on(176, 'b'); on(200, 'd', -5); on(205, 't'); on(215, 'b'); on(228, 'd', -6); on(232, 't'); on(244, 'd', -4)
on(212, 'B'); on(240, 'r'); plat(214, 22, 4); plat(220, 18, 4); put(221, 17, 'f')       # memory 7 (double-jump ledges)
block(198, 15, 204, 16); block(226, 14, 234, 15); plat(208, 16, 5)                      # high road across
put(193, 14, 'w')
# --- 250-300 second lake ---
pit(252, 296); plat(255, 25, 4); plat(262, 23, 3); plat(268, 25, 4); plat(275, 22, 3); plat(281, 24, 4); plat(288, 22, 4)
block(262, 12, 268, 13); put(265, 11, 'f'); JET.append((262, 23, 264, 12))               # memory 8 (jet off floating ledge)
for x in (258, 271, 285): put(x, 8, 'w')
on(266, 'd', -10); on(282, 'd', -8)
# --- 296-370 last gauntlet: vertical climb ---
ground(296, 310, 26); ground(310, 320, 24); ground(320, 330, 22); ground(330, 344, 25); ground(344, 360, 27); ground(360, 370, 26)
on(300, 'b'); on(306, 'd', -5); on(316, 't'); on(326, 'd', -6); on(338, 'b'); on(346, 'd', -5); on(352, 't'); on(364, 'd', -4)
plat(321, 17, 4); block(324, 7, 329, 8); put(326, 6, 'f'); JET.append((322, 17, 325, 7))  # memory 9 summit
DBL.append((320, 22, 321, 17))
plat(348, 22, 5); put(350, 21, 'f')                                                    # memory 10
on(304, 'B'); on(334, 'r'); on(342, 'L'); on(358, 'F')
# --- 370-440 torii arena (boss) ---
ground(370, 440, 27); on(372, 'L'); on(436, 'L'); on(405, 'T'); on(420, 'K', -7); on(410, 'B'); on(398, 'B')
plat(384, 23, 4); plat(424, 23, 4)
# --- 440-470 gate + car ---
ground(440, 470, 27); on(446, 'G'); on(452, 'A'); on(461, 'C'); on(467, 'R')
for y in range(H): M[y][0] = '#'; M[y][W - 1] = '#'
for x in range(W):
    if top[x] is None: continue
    for y in range(top[x], H): M[y][x] = '#'
for x, c, dy in ents: M[(top[x] if top[x] is not None else 26) - 1 + dy][x] = c
M[G - 2][4] = 'P'
fl = [(x, y) for y in range(H) for x in range(W) if M[y][x] == 'f']
out = "// generated by tools/build_level.py — do not hand edit\n" + \
  f"// reach checks [fromCol, fromRow(standing surface), toCol, toRow(surface)]\nexport const JET_CHECKS = {JET};\nexport const DBL_CHECKS = {DBL};\n" + \
  "export const LEVEL1 = [\n" + "\n".join("  '" + ''.join(r) + "'," for r in M) + "\n];\n"
open('src/scenes/level1Map.ts', 'w').write(out.replace('(', '[').replace(')', ']'))
print('flowers', len(fl))
