# pixel-exact one-way walk profiles for the giant setpieces (traced from art top edge near each deck line)
from PIL import Image; import json
D={'pr_torii_big':('torii',[[4,12,158],[36,24,146],[142,27,145],[153,16,164]]),'pr_lantern_stone':('lantern_stone',[[12,12,46],[54,12,46],[78,9,49],[99,2,55]]),'pr_stone_gate':('stone_gate',[[11,18,168]])}
out={}
for k,(f,decks) in D.items():
  im=Image.open(f'public/assets/props/{f}.png').convert('RGBA'); w,h=im.size; L=[]
  for di,(y,a,b) in enumerate(decks):
    up=10 if (k=='pr_lantern_stone' and di==0) or (k=='pr_torii_big' and di==0) else 4; p=[]
    for x in range(a,b+1):
      t=next((t for t in range(max(0,y-up),min(h,y+4)) if im.getpixel((x,t))[3]>128),y); p.append(t)
    for _ in range(3):
      for i in range(1,len(p)):
        if p[i]<p[i-1]-2: p[i]=p[i-1]-2
      for i in range(len(p)-2,-1,-1):
        if p[i]<p[i+1]-2: p[i]=p[i+1]-2
    L.append([a,p])
  out[k]=L
open('src/scenes/giantDecks.ts','w').write('// generated by tools/giant_decks.py\nexport const GIANT_DECKS: Record<string, [number, number[]][]> = '+json.dumps(out,separators=(',',':'))+';\n')
for k,v in out.items(): print(k,[ (a,min(p),max(p)) for a,p in v])
